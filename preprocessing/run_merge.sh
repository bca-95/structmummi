#!/bin/bash
set -euo pipefail

export TMPDIR=/scratch/SCRATCH_SAS/carene/tmp

# --- Locate the repo, wherever it was cloned
SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)" # ../structmummi/preprocessing
REPO_DIR="$(dirname "$SCRIPT_DIR")" # dirname remove the last part of the path # ../structmummi

# --- Find conda automatically
if ! command -v conda >/dev/null 2>&1; then
    echo "ERROR: conda not found in PATH" >&2; exit 1
fi
source "$(conda info --base)/etc/profile.d/conda.sh"
 
# conda's activation scripts use unset variables, which breaks "set -u"
set +u
conda deactivate
conda activate gcta_env
set -u

# script path
run_liftover="${SCRIPT_DIR}/run_liftover.sh" 
run_harmonization="${SCRIPT_DIR}/harmonization_to_1000g.sh"
plink2="${REPO_DIR}/external_tools/plink/plink2"

ref_1kG=""
ref_1kG_hg19="${REPO_DIR}/references/reference_1000G_hg19/1kG_MDS5"
ref_1kG_hg38="${REPO_DIR}/references/reference_1000G_hg38/allchr"


# Initialize variables
# The input should be the basename of plink file, eg. "data".bim
input_control=""
input_case=""
ref_hg_target=""
ref_fasta=""
convert_to_rsid="yes"
liftover="yes"
g1000_harmonization="yes"

# - For parsing argument - 
# Bash giveds to the script a list of words, where each word is considered
# as argument --> for instance : -i (arg 1) input.txt (arg 2) -o ...
while [[ $# -gt 0 ]]; do
  key="$1"
  case $key in
    --input_control)
      input_control="$2"
      shift 2
      ;;
    --input_case)
      input_case="$2"
      shift 2
      ;;

    --convert_to_rsid)
      convert_to_rsid="$2"
      shift 2
      ;;

    --liftover)
      liftover="$2"
      shift 2
      ;;

    --g1000_harmonization)
      g1000_harmonization="$2"
      shift 2
      ;;

    --ref_hg_target)
      ref_hg_target="$2"
      shift 2
      ;;

    *)
      echo "Unknown option: $1"
      echo "Usage: /pathtoscript/run_merge.sh --input_control plink_basename --input_case plink_basename --convert_to_rsid <yes or no (default: yes) --liftover <yes or no (default: yes)"
      exit 1
      ;;
  esac
done

if [[ "$ref_hg_target" == "hg19" ]]; then
    ref_1kG="$ref_1kG_hg19"
    ref_fasta="${REPO_DIR}/references/reference_hg19/Homo_sapiens.GRCh37.75.dna.primary_assembly.fa.gz"

elif [[ "$ref_hg_target" == "hg38" ]]; then
    ref_1kG="$ref_1kG_hg38"
    ref_fasta="${REPO_DIR}/references/reference_p14/Homo_sapiens.GRCh38.dna.primary_assembly.fa.gz"

fi


plink --bfile $input_control --make-bed --out "plink_control"
plink --bfile $input_case --make-bed --out "plink_case"


for dataset in "control" "case"; do

    # -- Make sure that the data for case and control are assigned to phenotype 2 or 1
    if [[ "$dataset" == "control" ]]; then
        mv plink_${dataset}.fam temp_plink_${dataset}.fam
        awk '{ $6=1; print }' temp_plink_${dataset}.fam > plink_${dataset}.fam

    elif [[ "$dataset" == "case" ]]; then
        mv plink_${dataset}.fam temp_plink_${dataset}.fam
        awk '{ $6=2; print }' temp_plink_${dataset}.fam > plink_${dataset}.fam
    fi

    # - Before merging, I need to remove sample with ambiguous sex
    # This need to be done before merging, not after
    # Before to avoid error during merging
    # Before not after merging because it will remove half of the sample (instead of 10-20 samples)
    # because two datasets have different allele orientations, and will exclude a lot
    
    # Sex quality control before merging, NOT after
    plink2 --bfile plink_${dataset} --check-sex max-female-xf=0.2 min-male-xf=0.8 --out  plink_${dataset} 
    
    # 1) Delete individuals with sex discrepancy.
    grep "PROBLEM" plink_${dataset}.sexcheck| awk '{print$1,$2}'> sex_${dataset}_discrepancy.txt
    
    # This command generates a list of individuals with the status <93>PROBLEM<94>.
    plink2 --bfile "plink_${dataset}" --remove "sex_${dataset}_discrepancy.txt" --make-bed --out "plink_${dataset}_2"

    # In the first step, convert the rsid in case and control to chr:pos
    # Inside run_harmonization, also convert the rsid to chr:pos

    plink2 --bfile "plink_${dataset}_2" --set-all-var-ids '@:#' --make-bed --out "plink_${dataset}_3"

    # remove duplicates, otherwise it generates error
    # and some variants might be missing but still present in the plink file
    # (for the data generated by illuminus, many variants are discarded)
    awk '$5 == "." || $6 == "."' plink_${dataset}_3.bim > bad_variants.txt
    cut -f2 bad_variants.txt > bad_variants.ids
    
    plink2 --bfile "plink_${dataset}_3" --exclude bad_variants.ids --make-bed --out "plink_${dataset}_3_fixed"


    plink2 --bfile "plink_${dataset}_3_fixed"  --rm-dup force-first --make-bed --out "plink_${dataset}_4"

    # ---  remove allele that are not the 4 bases
    plink2 --bfile "plink_${dataset}_4" --snps-only just-acgt --make-bed --out "plink_${dataset}_5"
 
done


# ------- Perform merging ----------
# First, perform merging where wtccc data is aligned on the control
# It can not be aligned to reference such 1000G and hg37/hg38 as the reference allele do not match yet.
# ((Before I did aligned case and control separately on ref hg38, then merge. But during the merging the reference allele is mixed again))
# -----------------------------------
# ------------------------------------
# --- Prior to merging 1000 Genomes data with the HapMap data we want to make sure that the files are mergeable, for this we conduct 3 steps:
# 1) Make sure the reference genome is similar in the HapMap and the 1000 Genomes Project datasets.
# 2) Resolve strand issues.
# 3) Remove the SNPs which after the previous two steps still differ between datasets.
#
# The following steps are maybe quite technical in terms of commands, but we just compare the two data sets and make sure they correspond.

# 1) set reference genome
awk '{print$2,$5}' plink_control_5.bim > control_ref-list.txt
plink --bfile plink_case_5 --reference-allele control_ref-list.txt --make-bed --out plink_case_6
# The case and the control have the same reference genome for all SNPs.
# This command will generate some warnings for impossible A1 allele assignment.

# 2) Resolve strand issues.
# Check for potential strand issues.
awk '{print$2,$5,$6}' plink_control_5.bim > plink_control_5_tmp
awk '{print$2,$5,$6}' plink_case_6.bim > plink_case_6_tmp
sort plink_control_5_tmp plink_case_6_tmp |uniq -u > all_differences.txt
# 1624 differences between the files, some of these might be due to strand issues.

## Flip SNPs for resolving strand issues.
# Print SNP-identifier and remove duplicates.
awk '{print$1}' all_differences.txt | sort -u > flip_list.txt
# Generates a file of 812 SNPs. These are the non-corresponding SNPs between the two files.
# Flip the 812 non-corresponding SNPs.
plink --bfile plink_case_6 --flip flip_list.txt --reference-allele control_ref-list.txt --make-bed --out plink_case_7

# Check for SNPs which are still problematic after they have been flipped.
awk '{print$2,$5,$6}' plink_case_7.bim > plink_case_7_tmp
sort plink_control_5_tmp plink_case_7_tmp |uniq -u  > uncorresponding_SNPs.txt
# This file demonstrates that there are 84 differences between the files.

# 3) Remove problematic SNPs from HapMap and 1000 Genomes.
awk '{print$1}' uncorresponding_SNPs.txt | sort -u > SNPs_for_exlusion.txt
# The command above generates a list of the 42 SNPs which caused the 84 differences between the HapMap and the 1000 Genomes data sets after flipping and setting of the reference genome.

# Remove the 42 problematic SNPs from both datasets.
plink --bfile plink_case_7 --exclude SNPs_for_exlusion.txt --make-bed --out plink_case_8
plink --bfile plink_control_5 --exclude SNPs_for_exlusion.txt --make-bed --out plink_control_6

# - Remove multiallelic variants because it can not be handle by plink
plink2 --bfile plink_control_6  --max-alleles 2 --make-bed --out plink_control_7
plink2 --bfile plink_case_8  --max-alleles 2 --make-bed --out plink_case_9


plink --bfile plink_case_9 --bmerge plink_control_7.bed plink_control_7.bim plink_control_7.fam --allow-no-sex --make-bed --out merged_data_1




# -- The genotype is aligned to the reference GRCh36,
# all tools and other genotype (such as the panle reference 1000 genomes) are mainly
# aligned to the reference GRCh37 or GRCh28
# This script will lift to GRCh37, but only the position (chr+pos) is updated
if [[ "$liftover" == "yes" ]]; then
   echo " ---> Your data are lifted to ${ref_hg_target} (from originally hg36)"
   bash "$run_liftover" --input_ "merged_data_1" --output_ "lifted_merged_data_1" --ref_hg_target "${ref_hg_target}"


   # if liftover performed, the information about the phenotype is dropped 
    # add them back
    awk '{print $1, $2, $6}' plink_case_9.fam > pheno_case.txt
    awk '{print $1, $2, $6}' plink_control_7.fam > pheno_control.txt

    cat pheno_case.txt pheno_control.txt > pheno_all.txt
fi


# - After the liftover, reset again the allele rsid to the lifted ID
plink2 --bfile "lifted_merged_data_1" --fa $ref_fasta --set-all-var-ids '@:#:$r:$a' --make-bed --out "lifted_merged_data_2"

# - Reset as while the individual ID (FID) which has been modified by "id-delim" to silence warning
#awk -F':' '{print $1, $2, 0, 0, 0, -9}' lifted_merged_data_2.fam > fid.fam
awk '{
  split($1, a, ":");
  print a[1], a[2], 0, 0, $5, $6
}' lifted_merged_data_2.fam > fid.fam

plink2 --bfile "lifted_merged_data_2" --fa $ref_fasta --fam fid.fam --make-bed --out "lifted_merged_data_3"

# - set the phenotype
plink2 --bfile "lifted_merged_data_3" --fa $ref_fasta --pheno pheno_all.txt --make-bed --out  "allvariants" #merged_data

