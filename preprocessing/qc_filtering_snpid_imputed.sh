#!/bin/bash
set -euo pipefail

export TMPDIR="${TMPDIR:-/tmp}"
export TMP="$TMPDIR"
export TEMP="$TMPDIR"
mkdir -p "$TMPDIR"

# --- Locate the repo, wherever it was cloned
SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)" # ../structmummi/preprocessing
REPO_DIR="$(dirname "$SCRIPT_DIR")" # dirname remove the last part of the path # ../structmummi

# --- Find conda automatically
if ! command -v conda >/dev/null 2>&1; then
    echo "ERROR: conda not found in PATH" >&2; exit 1
fi
source "$(conda info --base)/etc/profile.d/conda.sh"
 
# conda's activation scripts use unset variables, which breaks "set -u"
set +u
conda deactivate
conda activate gcta_env
set -u

# Default values
script_path="${SCRIPT_DIR}"
exon_bed_path=""
ref_fasta=""
ref_hg_target=""
maf=0.01
perform_imputation="yes"

# - For parsing argument - 
# Bash giveds to the script a list of words, where each word is considered
# as argument --> for instance : -i (arg 1) input.txt (arg 2) -o ...
while [[ $# -gt 0 ]]; do
  key="$1"
  case $key in
    --ref_hg_target)
      ref_hg_target="$2"
      shift 2
      ;;
    
    --maf)
      maf="$2"
      shift 2
      ;;

    --perform_imputation)
      perform_imputation="$2"
      shift 2
      ;;



    *)
      echo "Unknown option: $1"
      echo "Usage: /pathtoscript/qc_filtering_snpid_imputed.sh  --ref_hg_target <hg19 or hg38 (required)> --maf <float, default 0.01> --perform_imputation <yes or no, default: yes>"
      exit 1
      ;;
  esac
done


if [[ "$ref_hg_target" == "hg19" ]]; then
    ref_fasta="${REPO_DIR}/references/reference_hg19/Homo_sapiens.GRCh37.75.dna.primary_assembly.fa.gz"
    exon_bed_path="${REPO_DIR}/references/reference_hg19/exons_human.bed"
elif [[ "$ref_hg_target" == "hg38" ]]; then
    ref_fasta="${REPO_DIR}/references/reference_p14/Homo_sapiens.GRCh38.dna.primary_assembly.fa.gz"
    exon_bed_path="${REPO_DIR}/references/reference_p14/exons_human.bed"
fi


# if imputation is or not performed, modify the input file
if [[ "$perform_imputation" == "yes" ]]; then
    i_file="../plink_imp7_all"
elif [[ "$perform_imputation" == "no" ]]; then
    i_file="../plink13"
fi

### Step 1 ###

mkdir qc_imputed
cd qc_imputed

# the output of the first command have all variants (exons+intron)
# we only want to focus on the exons regions
plink2 --bfile  $i_file --extract range $exon_bed_path  --make-bed --out "plink"

# Investigate missingness per individual and per SNP and make histograms.
plink --bfile "plink" --missing

# Generate plots to visualize the missingness results.
Rscript --no-save "$script_path/hist_miss.R"

# The following two QC commands will not remove any SNPs or individuals. However, it is good practice to start the QC with these non-stringent thresholds.
# Delete SNPs with missingness >0.2.
plink2 --bfile "plink" --geno 0.2 --fa $ref_fasta  --make-bed --out "plink_2"

# Delete individuals with missingness >0.2.
plink2 --bfile "plink_2" --mind 0.2 --fa $ref_fasta --make-bed --out "plink_3"

# Delete SNPs with missingness >0.02.
plink2 --bfile "plink_3" --geno 0.02 --fa $ref_fasta  --make-bed --out "plink_4"

# Delete individuals with missingness >0.02.
plink2 --bfile "plink_4" --mind 0.02 --fa $ref_fasta --make-bed --out "plink_5"

## I checked sex disparency before merging
#plink --bfile "plink_5" --make-bed --out "plink_6"

###################################################
### Step 3 ###

# Generate a bfile with autosomal SNPs only and delete SNPs with a low minor allele frequency (MAF).

# Select autosomal SNPs only (i.e., from chromosomes 1 to 22).
awk '{ if ($1 >= 1 && $1 <= 22) print $2 }' "plink_5.bim" > snp_1_22.txt
plink2 --bfile "plink_5" --fa $ref_fasta --extract snp_1_22.txt --make-bed --out "plink_7"

# Generate a plot of the MAF distribution.
plink2 --bfile "plink_7" --fa $ref_fasta  --freq --out MAF_check
Rscript --no-save "$script_path/MAF_check.R"

# Remove SNPs with a low MAF frequency.
plink2 --bfile "plink_7" --fa $ref_fasta --ref-from-fa  --maf $maf --make-bed --out "plink_8"
# 1073226 SNPs are left
# A conventional MAF threshold for a regular GWAS is between 0.01 or 0.05, depending on sample size.


####################################################
### Step 4 ###


# Delete SNPs which are not in Hardy-Weinberg equilibrium (HWE).
# Check the distribution of HWE p-values of all SNPs.
# For hadry, when i use plink2 and there is large gap, it stucks

# with MS data, plink2 does work as there is something wrong with 3:195623143:G:A, but I was not able to spot the problem
# so, compute hardy with plink1.9

plink --bfile "plink_8" --hardy #--fa $ref_fasta 
# Selecting SNPs with HWE p-value below 0.00001, required for one of the two plot generated by the next Rscript, allows to zoom in on strongly deviating SNPs.
awk '{ if ($9 <0.00001) print $0 }' plink.hwe>plinkzoomhwe.hwe
Rscript --no-save "$script_path/hwe.R"

# By default the --hwe option in plink only filters for controls.
# Therefore, we use two steps, first we use a stringent HWE threshold for controls, followed by a less stringent threshold for the case data.
#plink --bfile "plink_8" --hwe 1e-6 --make-bed --out hwe_filter_step1
plink2 --bfile "plink_8" --fa $ref_fasta  --hwe 1e-6 keep-fewhet --make-bed --out "plink_9" # keep-fewhet added for MS or it failed

## The HWE threshold for the cases filters out only SNPs which deviate extremely from HWE.
## This second HWE step only focusses on cases because in the controls all SNPs with a HWE p-value < hwe 1e-6 were already removed
##plink --bfile hwe_filter_step1 --hwe 1e-10  include-nonctrl --make-bed --out "plink_9"

# Theoretical background for this step is given in our accompanying article: https://www.ncbi.nlm.nih.gov/pubmed/29484742 .
############################################################
### step 5 ###

# Generate a plot of the distribution of the heterozygosity rate of your subjects.
# And remove individuals with a heterozygosity rate deviating more than 3 sd from the mean.

# Checks for heterozygosity are performed on a set of SNPs which are not highly correlated.
# Therefore, to generate a list of non-(highly)correlated SNPs, we exclude high inversion regions (inversion.txt [High LD regions]) and prune the SNPs using the command --indep-pairwise<92>.
# The parameters <91>50 5 0.2<92> stand respectively for: the window size, the number of SNPs to shift the window at each step, and the multiple correlation coefficient for a SNP being regressed on all other SNPs simultaneously.

plink2 --bfile "plink_9" --fa $ref_fasta  --exclude range  "$script_path/inversion.txt" --indep-pairwise 50 5 0.2 --out indepSNP
# Note, don't delete the file indepSNP.prune.in, we will use this file in later steps of the tutorial.

plink2 --bfile "plink_9" --fa $ref_fasta  --extract indepSNP.prune.in --het --out R_check
# This file contains your pruned data set.

# Plot of the heterozygosity rate distribution
Rscript --no-save "$script_path/check_heterozygosity_rate.R"

# The following code generates a list of individuals who deviate more than 3 standard deviations from the heterozygosity rate mean.
# For data manipulation we recommend using UNIX. However, when performing statistical calculations R might be more convenient, hence the use of the Rscript for this step:
Rscript --no-save "$script_path/heterozygosity_outliers_list.R"

# Output of the command above: fail-het-qc.txt .
# When using our example data/the HapMap data this list contains 2 individuals (i.e., two individuals have a heterozygosity rate deviating more than 3 SD's from the mean).
# Adapt this file to make it compatible for PLINK, by removing all quotation marks from the file and selecting only the first two columns.
sed 's/"// g' fail-het-qc.txt | awk '{print$1, $2}'> het_fail_ind.txt

# Remove heterozygosity rate outliers.
plink2 --bfile "plink_9" --fa $ref_fasta  --remove het_fail_ind.txt --make-bed --out "plink_10"


############################################################
### step 6 ###
# It is essential to check datasets you analyse for cryptic relatedness.
# Assuming a random population sample we are going to exclude all individuals above the pihat threshold of 0.2 in this tutorial.

# Check for relationships between individuals with a pihat > 0.2.
plink --bfile "plink_10" --extract indepSNP.prune.in --genome --min 0.2 --out pihat_min0.2

# The HapMap dataset is known to contain parent-offspring relations.
# The following commands will visualize specifically these parent-offspring relations, using the z values.
awk '{ if ($8 >0.9) print $0 }' pihat_min0.2.genome>zoom_pihat.genome

# Generate a plot to assess the type of relationship.
Rscript --no-save "$script_path/Relatedness.R"

# The generated plots show a considerable amount of related individuals (explentation plot; PO = parent-offspring, UN = unrelated individuals) in the Hapmap data, this is expected since the dataset was constructed as such.
# Normally, family based data should be analyzed using specific family based methods. In this tutorial, for demonstrative purposes, we treat the relatedness as cryptic relatedness in a random population sample.
# In this tutorial, we aim to remove all 'relatedness' from our dataset.
# To demonstrate that the majority of the relatedness was due to parent-offspring we only include founders (individuals without parents in the dataset).

plink2 --bfile "plink_10" --fa $ref_fasta  --filter-founders --make-bed --out "plink_11"

# Now we will look again for individuals with a pihat >0.2.
plink --bfile "plink_11"  --extract indepSNP.prune.in --genome --min 0.2 --out pihat_min0.2_in_founders
# The file 'pihat_min0.2_in_founders.genome' shows that, after exclusion of all non-founders, only 1 individual pair with a pihat greater than 0.2 remains in the HapMap data.
# This is likely to be a full sib or DZ twin pair based on the Z values. Noteworthy, they were not given the same family identity (FID) in the HapMap data.

# For each pair of 'related' individuals with a pihat > 0.2, we recommend to remove the individual with the lowest call rate.
plink2 --bfile "plink_11"  --fa $ref_fasta  --missing
# Use an UNIX text editor (e.g., vi(m) ) to check which individual has the highest call rate in the 'related pair'.

# Generate a list of FID and IID of the individual(s) with a Pihat above 0.2, to check who had the lower call rate of the pair.
tail -n +2 pihat_min0.2_in_founders.genome | awk '{print $1, $2}' > 0.2_low_call_rate_pihat.txt

# Delete the individuals with the lowest call rate in 'related' pairs with a pihat > 0.2
plink2 --bfile "plink_11" --fa $ref_fasta  --remove 0.2_low_call_rate_pihat.txt --make-bed --out "plink_12"


